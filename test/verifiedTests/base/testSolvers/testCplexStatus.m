    [exitText, exitFlag] = cplexStatus(statusTable{i, 1});
    assert(strcmp(exitText, statusTable{i, 2}), 'text of status %d', statusTable{i, 1});
    assert(exitFlag == statusTable{i, 3}, 'flag of status %d', statusTable{i, 1});
end

%% the groups of exit flags

