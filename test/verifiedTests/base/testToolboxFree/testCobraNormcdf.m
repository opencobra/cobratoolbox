%       edge cases (sigma = 0, sigma < 0, NaN, Inf), scalar expansion and output size, the
%       'upper' tail, values against SciPy and against the MathWorks documentation, the errors
%       for unsupported options, and (only where the toolbox is installed) parity with normcdf.
%
% Function under test:
%     src/base/utilities/toolboxFree/cobraNormcdf.m
%
% Tier (Constitution III-Coverage):
%     Tier 1 - no model, no solver, hand-built inputs.
%
% Coverage exemptions:
