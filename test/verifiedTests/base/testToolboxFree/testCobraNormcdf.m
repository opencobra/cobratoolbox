% save the current path
currentDir = pwd;

% initialize the test
fileDir = fileparts(which('testCobraNormcdf'));
cd(fileDir);

% declare the requirements of this test. A Tier 1 test needs no solver, MATLAB toolbox
% or particular operating system, so none is listed; the call is the standard opening
% of a COBRA test and the place where a requirement would be added later
prepareTest();

% relative error over the entries whose reference is finite and non-zero; entries whose
% reference is 0 or +-Inf are compared exactly
isRelative = @(reference) reference ~= 0 & isfinite(reference);
relativeErrorOfColumns = @(value, reference) max([0; abs(value(isRelative(reference)) - reference(isRelative(reference))) ./ abs(reference(isRelative(reference)))]);
maxRelativeError = @(value, reference) relativeErrorOfColumns(value(:), reference(:));

%% call-site syntax normcdf(0, mu, sigma) with column vectors (directionalityReport, XomicsToModel)

% values from the SciPy grid below: N(1, 2^2) and N(-3, 0.5^2) at 0 (tolerance as for the grid)
meanValues = [1; -3];
sdValues = [2; 0.5];
p = cobraNormcdf(0, meanValues, sdValues);
assert(isequal(size(p), [2 1]) && isa(p, 'double'));
assert(maxRelativeError(p, [0.3085375387259869; 0.9999999990134123]) < 5e-14);

%% call-site syntax normcdf(0, mu, sigma, sigma): the 4th input (pCov) is ignored for one output

% thermoConstrainFluxBounds and forwardReversibleFigures pass the standard deviation as pCov
assert(isequal(cobraNormcdf(0, 1, 2, 2), cobraNormcdf(0, 1, 2)));
assert(isequal(cobraNormcdf(0, meanValues, sdValues, 3), cobraNormcdf(0, meanValues, sdValues)));
% a 5th numeric input (alpha) is ignored as well
assert(isequal(cobraNormcdf(0, 1, 2, [1 0; 0 1], 0.01), cobraNormcdf(0, 1, 2)));

%% call-site syntax normcdf(0, v, abs(v)/10) where v contains 0, so sigma = 0

% plotPredictedExchange: a zero flux gives sigma = 0 and x == mu, which is 1 (MathWorks doc:
% "p is 0 if x is smaller than mu, or 1 otherwise")
fluxValues = [-5; 0; 5];
p = cobraNormcdf(0, fluxValues, abs(fluxValues) / 10);
assert(isequal(p, [cobraNormcdf(0, -5, 0.5); 1; cobraNormcdf(0, 5, 0.5)]));
assert(p(1) == 1 && p(3) < 1e-20);

%% call-site syntax normcdf(0, mu, sigma, 'upper') (plotExperimentalvsPredictedExchange)

p = cobraNormcdf(0, meanValues, sdValues, 'upper');
assert(isequal(size(p), [2 1]));
assert(maxRelativeError(p, [0.6914624612740131; 9.865876450376946e-10]) < 5e-14);
% the option is case-insensitive and may be a string scalar
assert(isequal(cobraNormcdf(0, 1, 2, 'UPPER'), cobraNormcdf(0, 1, 2, "upper")));

%% default mean 0 and standard deviation 1

xValues = [-2 0 1.5];
assert(isequal(cobraNormcdf(xValues), cobraNormcdf(xValues, 0, 1)));
assert(isequal(cobraNormcdf(xValues, 0.5), cobraNormcdf(xValues, 0.5, 1)));
assert(isequal(cobraNormcdf(xValues, 'upper'), cobraNormcdf(xValues, 0, 1, 'upper')));
assert(cobraNormcdf(0) == 0.5);

%% MathWorks documentation example: the upper tail keeps its relative accuracy

% doc: normcdf(10,'upper') = 7.6199e-24 while 1 - normcdf(10) is 0
assert(abs(cobraNormcdf(10, 'upper') - 7.6199e-24) < 1e-28);
assert(1 - cobraNormcdf(10) == 0);

%% SciPy reference grid, lower and upper tail

% values generated by specs/20261103-120403-toolbox-free-replacements/references/distributions.py, SciPy 1.16.0, NumPy 1.26.4, mpmath 1.3.0
% normal: rows = x, columns = (mu, sigma) pairs
xGrid = [-40.0 -8.0 -1.0 0.0 0.5 3.0 40.0];
muSigma = [ ...
    0.0 1.0
    1.0 2.0
    -3.0 0.5
    ];
refLower = [ ...
    0.0 1.0764673258790346e-93 0.0
    6.22096057427174e-16 3.3976731247300535e-06 7.61985302416047e-24
    0.15865525393145707 0.15865525393145707 0.9999683287581669
    0.5 0.3085375387259869 0.9999999990134123
    0.6914624612740131 0.4012936743170763 0.9999999999987201
    0.9986501019683699 0.8413447460685429 1.0
    1.0 1.0 1.0
    ];
refUpper = [ ...
    1.0 1.0 1.0
    0.9999999999999993 0.9999966023268753 1.0
    0.8413447460685429 0.8413447460685429 3.167124183311986e-05
    0.5 0.6914624612740131 9.865876450376946e-10
    0.3085375387259869 0.5987063256829237 1.279812543885835e-12
    0.0013498980316300933 0.15865525393145707 1.776482112077653e-33
    0.0 5.489115475660254e-85 0.0
    ];
% normcdf and SciPy's ndtr are both built on the complementary error function. A tail
% probability at the standardized value z has relative condition number about z^2, so the
% rounding of z/sqrt(2) alone gives differences of about z^2*eps (6e-14 at z = -20.5), and in
% the far lower tail both deviate from the exact value by about 1e-14 (at x = -8 SciPy is 7e-15
% below the 40-digit mpmath value 6.220960574271784e-16, cobraNormcdf 6e-15 above it). The
% tolerance is therefore 2e-14 + 4*eps*z^2 relative, entry by entry.
for k = 1:size(muSigma, 1)
    zValues = (xGrid' - muSigma(k, 1)) / muSigma(k, 2);
    tolerance = 2e-14 + 4 * eps * zValues .^ 2;
    lowerValues = cobraNormcdf(xGrid', muSigma(k, 1), muSigma(k, 2));
    upperValues = cobraNormcdf(xGrid', muSigma(k, 1), muSigma(k, 2), 'upper');
    fprintf('cobraNormcdf vs SciPy, (mu, sigma) = (%g, %g): max relative error lower %.2e, upper %.2e\n', ...
        muSigma(k, 1), muSigma(k, 2), maxRelativeError(lowerValues, refLower(:, k)), maxRelativeError(upperValues, refUpper(:, k)));
    useLower = isRelative(refLower(:, k));
    useUpper = isRelative(refUpper(:, k));
    assert(all(abs(lowerValues(useLower) - refLower(useLower, k)) <= tolerance(useLower) .* abs(refLower(useLower, k))));
    assert(all(abs(upperValues(useUpper) - refUpper(useUpper, k)) <= tolerance(useUpper) .* abs(refUpper(useUpper, k))));
    assert(isequal(lowerValues(~useLower), refLower(~useLower, k)));
    assert(isequal(upperValues(~useUpper), refUpper(~useUpper, k)));
end

%% sigma = 0 is a step at mu; sigma < 0 gives NaN

assert(isequal(cobraNormcdf([-1 2 3], 2, 0), [0 1 1]));
assert(isequal(cobraNormcdf([-1 2 3], 2, 0, 'upper'), [1 0 0]));
assert(all(isnan(cobraNormcdf([-1 2 3], 2, -1))));
assert(all(isnan(cobraNormcdf([-1 2 3], 2, -1, 'upper'))));

%% NaN propagates, infinite x gives 0 or 1

assert(isnan(cobraNormcdf(NaN)) && isnan(cobraNormcdf(0, NaN)) && isnan(cobraNormcdf(0, 0, NaN)));
% the sigma = 0 step does not hide a NaN
assert(isnan(cobraNormcdf(NaN, 0, 0)) && isnan(cobraNormcdf(0, NaN, 0)));
assert(isequal(cobraNormcdf([-Inf Inf]), [0 1]) && isequal(cobraNormcdf([-Inf Inf], 'upper'), [1 0]));
% x = mu = Inf is undefined
assert(isnan(cobraNormcdf(Inf, Inf, 1)));

%% scalar expansion, output size and class

% the output takes the size of the non-scalar input
assert(isequal(size(cobraNormcdf(zeros(2, 3), 1, 2)), [2 3]));
assert(isequal(size(cobraNormcdf(0, ones(1, 4), 2)), [1 4]));
assert(isequal(size(cobraNormcdf(0, 1, 2 * ones(3, 1))), [3 1]));
assert(isequal(cobraNormcdf([0 1], [1 2], [2 3]), [cobraNormcdf(0, 1, 2) cobraNormcdf(1, 2, 3)]));
% empty input gives an empty output of the same size
assert(isequal(size(cobraNormcdf(zeros(0, 3), 1, 2)), [0 3]));
% single input gives single output
pSingle = cobraNormcdf(single(0.5));
assert(isa(pSingle, 'single') && abs(pSingle - single(0.6914624612740131)) < 1e-7);
% logical input is accepted as numeric
assert(cobraNormcdf(true) == cobraNormcdf(1));

%% errors: unsupported option, extra outputs, too many inputs, invalid and mismatched inputs

assert(verifyCobraFunctionError('cobraNormcdf', 'inputs', {0, 0, 1, 'lower'}, ...
    'testMessage', 'cobraNormcdf: unsupported option ''lower'' (only ''upper'' is supported).'));
assert(verifyCobraFunctionError('cobraNormcdf', 'inputs', {0, 0, 1, [1 0; 0 1]}, 'outputArgCount', 3, ...
    'testMessage', 'cobraNormcdf: the confidence bounds pLo and pUp are not supported (request one output).'));
assert(verifyCobraFunctionError('cobraNormcdf', 'inputs', {0, 0, 1, 1, 0.05, 1}));
assert(verifyCobraFunctionError('cobraNormcdf', 'inputs', {0, 'a', 1}, ...
    'testMessage', 'cobraNormcdf: inputs must be real numeric arrays.'));
assert(verifyCobraFunctionError('cobraNormcdf', 'inputs', {1i}));
assert(verifyCobraFunctionError('cobraNormcdf', 'inputs', {[0 1], [1 2 3]}, ...
    'testMessage', 'cobraNormcdf: non-scalar inputs must have the same size.'));

%% parity with normcdf (only where the Statistics and Machine Learning Toolbox is installed)

if exist('normcdf', 'file') == 2 && license('test', 'Statistics_Toolbox')
    rng(20261103);
    xRandom = 3 * randn(200, 1);
    muRandom = randn(200, 1);
    sigmaRandom = 0.5 + 2 * rand(200, 1);
    sigmaRandom(1:10) = 0;
    xRandom(1:5) = muRandom(1:5);
    % both evaluate erfc of the same argument: same entry-wise tolerance as the SciPy grid;
    % the sigma = 0 step must match exactly
    isStep = sigmaRandom == 0;
    zRandom = (xRandom - muRandom) ./ sigmaRandom;
    tolerance = 2e-14 + 4 * eps * zRandom .^ 2;
    for tail = {{}, {'upper'}}
        pCobra = cobraNormcdf(xRandom, muRandom, sigmaRandom, tail{1}{:});
        pMathWorks = normcdf(xRandom, muRandom, sigmaRandom, tail{1}{:});
        assert(isequal(pCobra(isStep), pMathWorks(isStep)));
        assert(all(abs(pCobra(~isStep) - pMathWorks(~isStep)) <= tolerance(~isStep) .* abs(pMathWorks(~isStep))));
    end
    % call-site syntax with the 4th input
    pCobra = cobraNormcdf(0, muRandom(20), sigmaRandom(20), sigmaRandom(20));
    pMathWorks = normcdf(0, muRandom(20), sigmaRandom(20), sigmaRandom(20));
    assert(abs(pCobra - pMathWorks) <= 5e-14 * abs(pMathWorks));
    fprintf('parity with normcdf: passed\n');
else
    fprintf('skipped: Statistics and Machine Learning Toolbox not installed\n');
end

