%% parity with corr (only where the Statistics and Machine Learning Toolbox is installed)

if exist('corr', 'file') == 2 && license('test', 'Statistics_Toolbox')
    % same formulas: coefficients 1e-13, p-values 1e-10 relative (the toolbox may evaluate the t
    % and normal tails with other routines); every p-value rule is exercised
    parityCases = {{XP, YP}, {x7, y7}, {x8t, y8t}, {x12, y12m}, {x12, y12w}, {x15t, y15t}, ...
        {x15t(1:9), y15t(1:9)}, {x15t(1:10), y15t(1:10)}, {matrixData, matrixData}};
    for n = [49 50 60]
        [xFormula, yFormula] = formulaData(n);
        parityCases{end + 1} = {xFormula, yFormula}; %#ok<SAGROW>
    end
    for corrType = {'Pearson', 'Spearman', 'Kendall'}
        for k = 1:numel(parityCases)
            [rhoCobra, pCobra] = cobraCorr(parityCases{k}{1}, parityCases{k}{2}, 'Type', corrType{1});
            [rhoMathWorks, pMathWorks] = corr(parityCases{k}{1}, parityCases{k}{2}, 'Type', corrType{1});
            assert(max(abs(rhoCobra(:) - rhoMathWorks(:))) < 1e-13);
            assert(max(abs(pCobra(:) - pMathWorks(:)) ./ max(pMathWorks(:), 1e-300)) < 1e-10 || max(abs(pCobra(:) - pMathWorks(:))) < 1e-15);
        end
        [rhoCobra, pCobra] = cobraCorr(matrixWithNaN, 'Type', corrType{1});
        [rhoMathWorks, pMathWorks] = corr(matrixWithNaN, 'Type', corrType{1});
        assert(isequal(isnan(rhoCobra), isnan(rhoMathWorks)) && isequal(isnan(pCobra), isnan(pMathWorks)));
    end
    fprintf('parity with corr: passed\n');
else
    fprintf('skipped: Statistics and Machine Learning Toolbox not installed\n');
end

