    'testMessage', 'cobraFcdf: unsupported option ''lower'' (only ''upper'' is supported).'));
assert(verifyCobraFunctionError('cobraFcdf', 'inputs', {1, 2, 3, 4}, ...
    'testMessage', 'cobraFcdf: unsupported option ''double'' (only ''upper'' is supported).'));
assert(verifyCobraFunctionError('cobraFcdf', 'inputs', {1, 2, 3, 'upper', 'upper'}));
assert(verifyCobraFunctionError('cobraFcdf', 'inputs', {1, 'a', 2}, ...
    'testMessage', 'cobraFcdf: inputs must be real numeric arrays.'));
assert(verifyCobraFunctionError('cobraFcdf', 'inputs', {[1 2], [1 2 3], 2}, ...
    'testMessage', 'cobraFcdf: non-scalar inputs must have the same size.'));

