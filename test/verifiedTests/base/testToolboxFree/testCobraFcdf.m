% fcdf is betainc and SciPy's f uses Boost's ibeta; for infinite degrees of freedom both use the
% chi-square limit (gammainc / igam). Agreement is a few units in the last place except for
% (v1, v2) = (0.5, 100), where MATLAB's betainc with b = 50 is 2.4e-13 relative off the 40-digit
% mpmath value (SciPy matches mpmath to 1e-15), hence 1e-12 relative
for k = 1:size(v1v2, 1)
    lowerValues = cobraFcdf(xGrid', v1v2(k, 1), v1v2(k, 2));
    upperValues = cobraFcdf(xGrid', v1v2(k, 1), v1v2(k, 2), 'upper');
    fprintf('cobraFcdf vs SciPy, (v1, v2) = (%g, %g): max relative error lower %.2e, upper %.2e\n', ...
        v1v2(k, 1), v1v2(k, 2), maxRelativeError(lowerValues, refLower(:, k)), maxRelativeError(upperValues, refUpper(:, k)));
    assert(maxRelativeError(lowerValues, refLower(:, k)) < 1e-12);
    assert(maxRelativeError(upperValues, refUpper(:, k)) < 1e-12);
    assert(isequal(lowerValues(~isRelative(refLower(:, k))), refLower(~isRelative(refLower(:, k)), k)));
    assert(isequal(upperValues(~isRelative(refUpper(:, k))), refUpper(~isRelative(refUpper(:, k)), k)));
