%% edge cases: x <= 0 and x = Inf; v1 or v2 <= 0 and NaN give NaN; step when both are Inf

assert(isequal(cobraFcdf([-Inf -1 0 Inf], 3, 4), [0 0 0 1]));
assert(isequal(cobraFcdf([-Inf -1 0 Inf], 3, 4, 'upper'), [1 1 1 0]));
assert(isequal(cobraFcdf([0.5 1 2], Inf, Inf), [0 1 1]));
assert(isequal(cobraFcdf([0.5 1 2], Inf, Inf, 'upper'), [1 0 0]));
assert(all(isnan(cobraFcdf(ones(1, 5), [0 -1 NaN 2 2], [2 2 2 0 NaN]))));
assert(isnan(cobraFcdf(NaN, 3, 4)) && isnan(cobraFcdf(NaN, 3, 4, 'upper')));

%% scalar expansion, output size and class

assert(isequal(size(cobraFcdf(ones(2, 3), 4, 5)), [2 3]));
assert(isequal(size(cobraFcdf(1, [1 2 3 4], 5)), [1 4]));
assert(isequal(size(cobraFcdf(1, 2, [1; 2; 3])), [3 1]));
assert(isequal(cobraFcdf([1 2], [3 4], [5 6]), [cobraFcdf(1, 3, 5) cobraFcdf(2, 4, 6)]));
assert(isequal(size(cobraFcdf(zeros(0, 3), 2, 3)), [0 3]));
pSingle = cobraFcdf(single(3), 2.5, 10);
assert(isa(pSingle, 'single') && abs(pSingle - single(0.9120864458706704)) < 1e-7);

%% errors: unsupported option and invalid or mismatched inputs

