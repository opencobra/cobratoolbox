    assert(maxRelativeError(cobraFcdf(xRandom, v1Random, v2Random), fcdf(xRandom, v1Random, v2Random)) < 1e-10);
    assert(maxRelativeError(cobraFcdf(xRandom, v1Random, v2Random, 'upper'), fcdf(xRandom, v1Random, v2Random, 'upper')) < 1e-10);
