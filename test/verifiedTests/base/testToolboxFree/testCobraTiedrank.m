% Purpose:
%     - cobraTiedrank is the plain-MATLAB replacement for tiedrank (Statistics and Machine
%       Learning Toolbox). This test checks the documented example, column-wise ranking of a
%       matrix with NaN, ties and repeated Inf, row and column vectors, empty and all-NaN
%       columns, the tie adjustment, the errors for unsupported options and invalid input, and
%       (only where the toolbox is installed) parity with tiedrank.
%
% Function under test:
%     src/base/utilities/toolboxFree/cobraTiedrank.m
%
% Tier (Constitution III-Coverage):
%     Tier 1 - no model, no solver, hand-built inputs.
%
% Coverage exemptions:
%     None. Every executable line is reached below.
%
% Known defects documented (NOT tested, NOT fixed here):
%     None found.
%
% Authors:
%     - Generated for feature 20261111-152503-toolbox-free-remaining, 2026-11-11.

% save the current path
currentDir = pwd;

% initialize the test
fileDir = fileparts(which('testCobraTiedrank'));
cd(fileDir);

% declare the requirements of this test. A Tier 1 test needs no solver, MATLAB toolbox
% or particular operating system, so none is listed; the call is the standard opening
% of a COBRA test and the place where a requirement would be added later
prepareTest();

%% documented example: tiedrank([-2 1 3 1 4]) = [1 2.5 4 2.5 5], tieadj = 3

[ranks, tieadj] = cobraTiedrank([-2 1 3 1 4]);
% ranks are averages of integers, so they are exact
assert(isequal(ranks, [1 2.5 4 2.5 5]));
assert(isequal(tieadj, 3));

%% matrix with NaN, ties and repeated Inf, ranked column by column

% values generated by specs/20261111-152503-toolbox-free-remaining/references/g1_stats.py
% (section tiedrank), SciPy 1.16.3 rankdata(method='average', axis=0, nan_policy='omit')
xMatrix = [3.0 0.5; NaN 0.5; 1.0 NaN; 1.0 NaN; 2.0 -1.0; 3.0 Inf; 3.0 Inf];
refRanks = [5.0 2.5; NaN 2.5; 1.5 NaN; 1.5 NaN; 3.0 1.0; 5.0 4.5; 5.0 4.5];
[ranks, tieadj] = cobraTiedrank(xMatrix);
% exact: same NaN positions and identical (half-integer) ranks; two Inf values are a tie
assert(isequal(isnan(ranks), isnan(refRanks)));
assert(isequal(ranks(~isnan(ranks)), refRanks(~isnan(refRanks))));
assert(isequal(tieadj, [15 6]));

%% orientation, logical input, empty and all-NaN columns

assert(isequal(cobraTiedrank([2; 1; 2]), [2.5; 1; 2.5]));
assert(isequal(cobraTiedrank(logical([1 0 1])), [2.5 1 2.5]));
[ranks, tieadj] = cobraTiedrank([NaN 1; NaN 1]);
assert(all(isnan(ranks(:, 1))) && isequal(ranks(:, 2), [1.5; 1.5]));
assert(isequal(tieadj, [0 3]));
[ranks, tieadj] = cobraTiedrank(zeros(0, 1));
assert(isempty(ranks) && isequal(tieadj, 0));
assert(isequal(cobraTiedrank(single([3 1 2])), [3 1 2]) && isa(cobraTiedrank(single(1)), 'double'));

%% errors: the tieflag and bidir arguments and invalid input

assert(verifyCobraFunctionError('cobraTiedrank', 'inputs', {[1 2], 1}, ...
    'testMessage', 'cobraTiedrank: unsupported option ''tieflag'' (only the syntax cobraTiedrank(x) is supported).'));
assert(verifyCobraFunctionError('cobraTiedrank', 'inputs', {[1 2], 0, 1}, ...
    'testMessage', 'cobraTiedrank: unsupported option ''bidir'' (only the syntax cobraTiedrank(x) is supported).'));
assert(verifyCobraFunctionError('cobraTiedrank', 'inputs', {{1, 2}}, ...
    'testMessage', 'cobraTiedrank: x must be a real numeric or logical vector or matrix.'));
assert(verifyCobraFunctionError('cobraTiedrank', 'inputs', {ones(2, 2, 2)}));

%% parity with tiedrank (only where the Statistics and Machine Learning Toolbox is installed)

if exist('tiedrank', 'file') == 2 && license('test', 'Statistics_Toolbox')
    rng(20261111);
    xRandom = round(5 * randn(40, 3));
    xRandom(rand(40, 3) < 0.1) = NaN;
    [ranks, tieadj] = cobraTiedrank(xRandom);
    [ranksToolbox, tieadjToolbox] = tiedrank(xRandom);
    assert(isequaln(ranks, ranksToolbox) && isequal(tieadj, tieadjToolbox));
    fprintf('parity with tiedrank: passed\n');
else
    fprintf('skipped: Statistics and Machine Learning Toolbox not installed\n');
end

% change the directory
cd(currentDir)
