% Tolerances (relative unless stated): the Hald design [1 X] is ill-conditioned (cond about
% 8e3, the 4 ingredients sum to about 100), so coefficients from a QR solve (MATLAB) and an SVD
% solve (lstsq) agree to about cond*eps = 2e-12 relative to |b|; 1e-10 relative to max|b| is
% used for b and bint, 1e-10 for residuals relative to max|r|, and 1e-11 for the stats (R2,
% F, s2 depend on the residual sum of squares, which is stationary in b, so they are better
% conditioned; pF adds the F tail's condition number, about 10 here). The straight-line
% design is well conditioned: 1e-12.
maxRel = @(a, b) max(abs(a(:) - b(:)) ./ max(abs(b(:)), realmin));
maxScaled = @(a, b) max(abs(a(:) - b(:))) / max(abs(b(:)));

