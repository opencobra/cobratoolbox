%% rank-deficient design: warning, and the dropped column gets b = 0 and bint = [0 0]

% [x, 2x, ones]: QR with column pivoting keeps 2x and ones (SciPy pivots [1, 2, 0]) and drops x
lastwarn('');
[b, bint, ~, ~, stats] = cobraRegress(yLine, [xLine 2 * xLine ones(11, 1)]);
[warningMessage, warningId] = lastwarn;
assert(strcmp(warningId, 'cobraRegress:RankDefDesignMat') && strcmp(warningMessage, 'X is rank deficient to within machine precision.'));
assert(b(1) == 0 && isequal(bint(1, :), [0 0]));
assert(maxRel(b(2:3), refBRankDef(2:3)') < 1e-12 && maxRel(bint(2:3, :), refBintRankDef(2:3, :)) < 1e-12);
% the degrees of freedom use the rank (2), not the number of columns (3)
assert(maxRel(stats, refStatsRankDef) < 1e-12);

%% no constant term: warning when stats are requested, R2 computed about the mean

lastwarn('');
[~, ~, ~, ~, stats] = cobraRegress(yLine, xLine + 1);
[warningMessage, warningId] = lastwarn;
assert(strcmp(warningId, 'cobraRegress:NoConst') && ...
    strcmp(warningMessage, 'R-square and the F statistic are not well-defined unless X has a column of ones.'));
% one column of rank 1: F and its p-value are NaN
assert(isnan(stats(2)) && isnan(stats(3)));
% R2 = 1 - SSE/TSS with the centred TSS
bOrigin = (xLine + 1) \ yLine;
residual = yLine - (xLine + 1) * bOrigin;
assert(abs(stats(1) - (1 - sum(residual .^ 2) / sum((yLine - mean(yLine)) .^ 2))) < 1e-12);
% a column of twos is an implied constant: no warning
lastwarn('');
cobraRegress(yLine, [xLine 2 * ones(11, 1)]);
[~, ~, ~, ~, stats] = cobraRegress(yLine, [xLine 2 * ones(11, 1)]);
assert(isempty(lastwarn) && abs(stats(1) - refStatsLine(1)) < 1e-12);
% a constant implied by dummy columns that sum to one raises no warning
lastwarn('');
groupA = double(xLine < 0.5);
[~, ~, ~, ~, stats] = cobraRegress(yLine, [groupA 1 - groupA xLine]);
assert(isempty(lastwarn) && all(isfinite(stats)));
% without stats there is no constant check and no warning
lastwarn('');
cobraRegress(yLine, xLine + 1);
assert(isempty(lastwarn));

%% one residual degree of freedom: nu = 1 branch of the residual intervals

% rint = r -/+ tinv(1-alpha/2, 1)*sqrt(1-h)*rmse (no leave-one-out estimate exists with nu = 1);
% the reference uses the same formula, so it checks the branch, not MathWorks' choice of t
[b, bint, r, rint, stats] = cobraRegress([1.0; 2.9; 5.2], [[0; 1; 2] ones(3, 1)]);
assert(maxRel(b, refBNu1') < 1e-12 && maxRel(bint, refBintNu1) < 1e-12);
assert(maxScaled(r, refRNu1') < 1e-12 && maxScaled(rint, refRintNu1) < 1e-12);
assert(maxRel(stats, refStatsNu1) < 1e-12);
% a point of leverage 1 (the only observation at x = 5 with a group dummy) gets an infinite interval
[~, ~, r, rint] = cobraRegress([1; 2; 3; 9], [1 0; 1 0; 1 0; 0 1]);
assert(abs(r(4)) < 1e-14 && isequal(rint(4, :), [-Inf Inf]) && all(isfinite(rint(1:3, :)), 'all'));
[~, ~, ~, rint] = cobraRegress([1; 2; 9], [1 0; 1 0; 0 1]);
assert(isequal(rint(3, :), [-Inf Inf]) && all(isfinite(rint(1:2, :)), 'all'));

%% exactly determined fit: nu = 0, s2 = NaN, NaN intervals of the estimated coefficients

[b, bint, ~, ~, stats] = cobraRegress([1; 3], [1 0; 1 1]);
assert(max(abs(b - [1; 2])) < 1e-14 && all(isnan(bint(:))));
assert(abs(stats(1) - 1) < 1e-14 && isnan(stats(2)) && isnan(stats(3)) && isnan(stats(4)));

%% no complete row: rank 0, zeros in b and bint, NaN residuals and stats, rank warning

