% the columns exercise both betainc argument forms (x.^2 >= nu and x.^2 < nu) for every finite
% nu and the normal cdf for nu = Inf. SciPy uses Boost's incomplete beta function, which is
% accurate here to about 1e-14 against 60-digit mpmath values; the differences are the known
% inaccuracy of MATLAB's betainc, which grows with nu (see the cobraTcdf NOTE). The tolerance
% of each column is about three times the largest difference measured on 2026-11-03:
% nu <= 10: 6.1e-14; nu = 1000: 7.1e-13; nu = 9000: 9.0e-12; nu = 1e6: 1.6e-9; Inf: 1.3e-14.
% Where SciPy returns 0 the true value is below 1e-300 (for nu = 9000 and x = -40 it is the
% subnormal 1.77e-322, which SciPy flushes to 0), so values below 1e-300 are accepted there.
columnTolerance = [2e-13 2e-13 2e-13 2e-13 2e-12 3e-11 5e-9 5e-14];
for k = 1:numel(nuGrid)
    lowerValues = cobraTcdf(xGrid', nuGrid(k));
    upperValues = cobraTcdf(xGrid', nuGrid(k), 'upper');
    fprintf('cobraTcdf vs SciPy, nu = %g: max relative error lower %.2e, upper %.2e\n', ...
        nuGrid(k), maxRelativeError(lowerValues, refLower(:, k)), maxRelativeError(upperValues, refUpper(:, k)));
    assert(maxRelativeError(lowerValues, refLower(:, k)) < columnTolerance(k));
    assert(maxRelativeError(upperValues, refUpper(:, k)) < columnTolerance(k));
    assert(isequal(lowerValues(isinf(refLower(:, k))), refLower(isinf(refLower(:, k)), k)));
    assert(isequal(upperValues(isinf(refUpper(:, k))), refUpper(isinf(refUpper(:, k)), k)));
    assert(all(abs(lowerValues(refLower(:, k) == 0)) < 1e-300) && all(abs(upperValues(refUpper(:, k) == 0)) < 1e-300));
end

%% the normal cdf above nu = 1e7, betainc up to it (R14 MathWorks rule)

xSwitch = [-30 -8 -1 0.5 4]';
% (the smaller tail is erfc(|x|/sqrt(2))/2 and the other tail its complement)
normalTail = 0.5 * erfc(abs(xSwitch) / sqrt(2));
assert(isequal(cobraTcdf(xSwitch, 1e7 + 1), [normalTail(xSwitch < 0); 1 - normalTail(xSwitch > 0)]));
assert(isequal(cobraTcdf(xSwitch, Inf), cobraTcdf(xSwitch, 1e8)));
% at nu = 1e7 betainc is used: it differs from the normal cdf by the t correction
% (about 1e-4 relative at x = -8) plus betainc's error (about 2e-8 relative)
assert(cobraTcdf(-8, 1e7) ~= cobraTcdf(-8, 1e7 + 1));
% (40-digit mpmath value 6.221617401403393e-16; measured betainc error 1.1e-8, so 5e-8)
assert(abs(cobraTcdf(-8, 1e7) / 6.221617401403393e-16 - 1) < 5e-8);
% known difference from the exact value: where x.^2 overflows (|x| > 1e154) the tail is 0, even
% for nu = 1 where the exact value 1/(pi*1e200) is representable
assert(isequal(cobraTcdf([-1e200 1e200], 1), [0 1]));
assert(isequal(cobraTcdf([-1e200 1e200], 1e5), [0 1]));

%% the Cauchy distribution (nu = 1) has a closed form

xCauchy = [-1e8 -40 -1 -0.01 0.3 2 1e8]';
% P(T < x) = 1/2 + atan(x)/pi; the closed form loses relative accuracy for x << 0, so the
% left tail is checked through atan(-1/x)/pi = P(T < x) for x < 0
cauchyLower = 0.5 + atan(xCauchy) / pi;
cauchyLower(xCauchy < 0) = atan(-1 ./ xCauchy(xCauchy < 0)) / pi;
assert(maxRelativeError(cobraTcdf(xCauchy, 1), cauchyLower) < 1e-14);

%% edge cases: nu <= 0 and NaN give NaN; +-Inf, x = 0 and non-integer nu

assert(all(isnan(cobraTcdf([1 1 1], [0 -2 NaN]))));
assert(isnan(cobraTcdf(NaN, 3)) && isnan(cobraTcdf(NaN, 3, 'upper')));
assert(isequal(cobraTcdf([-Inf 0 Inf], 2.5), [0 0.5 1]));
assert(isequal(cobraTcdf([-Inf 0 Inf], 2.5, 'upper'), [1 0.5 0]));
assert(isequal(cobraTcdf([-Inf 0 Inf], 1e6), [0 0.5 1]));
assert(isequal(cobraTcdf([-Inf 0 Inf], Inf), [0 0.5 1]));

%% scalar expansion, output size and class

assert(isequal(size(cobraTcdf(zeros(2, 3), 4)), [2 3]));
assert(isequal(size(cobraTcdf(1, [1 2 3 4])), [1 4]));
assert(isequal(cobraTcdf([1 2], [3 4]), [cobraTcdf(1, 3) cobraTcdf(2, 4)]));
assert(isequal(size(cobraTcdf(zeros(0, 3), 2)), [0 3]));
pSingle = cobraTcdf(single(-1), 10);
assert(isa(pSingle, 'single') && abs(pSingle - single(0.17044656615103004)) < 1e-7);

