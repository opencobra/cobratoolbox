    nuRandom = [0.5 + 30 * rand(190, 1); 1; 2; 1000; 5e4; 1e6; Inf; 0.7; 3; 10; 100];
    isModerate = nuRandom <= 1000 | nuRandom == Inf;
    % the same R14 rule and the same betainc for nu <= 1e7: 1e-12 relative for nu <= 1000 and
    % Inf; for larger nu the MathWorks choice between the two betainc argument forms is not
    % documented and betainc's error there is up to about 2e-9 (nu = 1e6), hence 1e-8
    for tail = {{}, {'upper'}}
        pCobra = cobraTcdf(xRandom, nuRandom, tail{1}{:});
        pMathWorks = tcdf(xRandom, nuRandom, tail{1}{:});
        assert(maxRelativeError(pCobra(isModerate), pMathWorks(isModerate)) < 1e-12);
        assert(maxRelativeError(pCobra(~isModerate), pMathWorks(~isModerate)) < 1e-8);
    end
    fprintf('parity with tcdf: passed\n');
