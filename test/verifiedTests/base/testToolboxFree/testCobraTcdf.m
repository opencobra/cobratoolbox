% relative error over the entries whose reference is finite and non-zero; entries whose
% reference is 0 or +-Inf are compared exactly
isRelative = @(reference) reference ~= 0 & isfinite(reference);
relativeErrorOfColumns = @(value, reference) max([0; abs(value(isRelative(reference)) - reference(isRelative(reference))) ./ abs(reference(isRelative(reference)))]);
maxRelativeError = @(value, reference) relativeErrorOfColumns(value(:), reference(:));

%% syntax tcdf(x, nu) and tcdf(x, nu, 'upper')

% MathWorks documentation of tinv: tinv(0.95, 10) = 1.8125, so tcdf(1.8125, 10) is 0.95 to the
% four digits published (SciPy: t.cdf(1.8125, 10) = 0.9500031714760766)
assert(abs(cobraTcdf(1.8125, 10) - 0.95) < 5e-5);
assert(maxRelativeError(cobraTcdf(1.8125, 10), 0.9500031714760766) < 1e-14);
% the upper tail equals the lower tail at -x (symmetry) and complements the lower tail
xValues = [-3 -0.2 0 0.7 5];
assert(isequal(cobraTcdf(xValues, 4, 'upper'), cobraTcdf(-xValues, 4)));
assert(max(abs(cobraTcdf(xValues, 4, 'upper') + cobraTcdf(xValues, 4) - 1)) < 1e-15);
% the option is case-insensitive and may be a string scalar
assert(isequal(cobraTcdf(2, 3, 'Upper'), cobraTcdf(2, 3, "upper")));

