% The COBRAToolbox: testCobraNorminv.m
%
% Purpose:
%     - cobraNorminv is the plain-MATLAB replacement for norminv (Statistics and Machine Learning
%       Toolbox). This test checks the syntax used by the call site in src/, the documented edge
%       cases (p = 0, p = 1, p outside [0, 1], sigma <= 0, NaN), scalar expansion and output
%       size, values against SciPy and against the MathWorks documentation, the errors for
%       invalid inputs, and (only where the toolbox is installed) parity with norminv.
%
% Function under test:
%     src/base/utilities/toolboxFree/cobraNorminv.m
%
% Tier (Constitution III-Coverage):
%     Tier 1 - no model, no solver, hand-built inputs.
%
% Coverage exemptions:
%     None. Every executable line is reached below.
%
% Known defects documented (NOT tested, NOT fixed here):
%     None found.
%
% Authors:
%     - Generated for feature 20261103-120403-toolbox-free-replacements, 2026-11-03.

% save the current path
currentDir = pwd;

% initialize the test
fileDir = fileparts(which('testCobraNorminv'));
cd(fileDir);

% declare the requirements of this test. A Tier 1 test needs no solver, MATLAB toolbox
% or particular operating system, so none is listed; the call is the standard opening
% of a COBRA test and the place where a requirement would be added later
prepareTest();

% relative error over the entries whose reference is finite and non-zero; entries whose
% reference is 0 or +-Inf are compared exactly
isRelative = @(reference) reference ~= 0 & isfinite(reference);
relativeErrorOfColumns = @(value, reference) max([0; abs(value(isRelative(reference)) - reference(isRelative(reference))) ./ abs(reference(isRelative(reference)))]);
maxRelativeError = @(value, reference) relativeErrorOfColumns(value(:), reference(:));

%% call-site syntax norminv(p/2) with a column of p-values (runNonparametricTests)

pValues = [0.05; 1e-10; 1];
z = cobraNorminv(pValues / 2);
assert(isequal(size(z), [3 1]) && isa(z, 'double'));
% norminv(0.025) = -1.959963984540054 (SciPy reference grid below), norminv(0.5) = 0
assert(maxRelativeError(z(1), -1.9599639845400545) < 1e-14 && z(3) == 0);
assert(isequal(cobraNorminv(pValues / 2), cobraNorminv(pValues / 2, 0, 1)));

%% MathWorks documentation examples

% doc: norminv(0.975) = 1.9600 (two-sided 95% interval)
assert(abs(cobraNorminv(0.975) - 1.9600) < 5e-5);
% doc: norminv(0:0.25:1) = [-Inf -0.6745 0 0.6745 Inf]
x = cobraNorminv(0:0.25:1);
assert(isequal(x([1 3 5]), [-Inf 0 Inf]) && all(abs(x([2 4]) - [-0.6745 0.6745]) < 5e-5));

%% SciPy reference grid

% values generated by specs/20261103-120403-toolbox-free-replacements/references/distributions.py, SciPy 1.16.0, NumPy 1.26.4, mpmath 1.3.0
% normal quantiles: rows = p, columns = (mu, sigma) pairs
pGrid = [1e-300 1e-10 0.025 0.5 0.95 0.999999999999];
muSigma = [ ...
    0.0 1.0
    1.0 2.0
    -3.0 0.5
    ];
refInv = [ ...
    -37.0470962993612 -73.0941925987224 -21.5235481496806
    -6.361340902404056 -11.722681804808111 -6.180670451202028
    -1.9599639845400545 -2.919927969080109 -3.9799819922700275
    0.0 1.0 -3.0
    1.6448536269514722 4.289707253902945 -2.177573186524264
    7.0344869100478356 15.068973820095671 0.5172434550239178
    ];
% norminv evaluates erfcinv, SciPy's ndtri a rational approximation: both are accurate to a
% few units in the last place; 1e-14 relative bounds the difference with margin
for k = 1:size(muSigma, 1)
    xValues = cobraNorminv(pGrid', muSigma(k, 1), muSigma(k, 2));
    fprintf('cobraNorminv vs SciPy, (mu, sigma) = (%g, %g): max relative error %.2e\n', ...
        muSigma(k, 1), muSigma(k, 2), maxRelativeError(xValues, refInv(:, k)));
    assert(maxRelativeError(xValues, refInv(:, k)) < 1e-14);
    assert(isequal(xValues(~isRelative(refInv(:, k))), refInv(~isRelative(refInv(:, k)), k)));
end

%% round trip with cobraNormcdf

pRoundTrip = [1e-12 0.01 0.3 0.5 0.8 0.99];
assert(max(abs(cobraNormcdf(cobraNorminv(pRoundTrip, 2, 3), 2, 3) - pRoundTrip) ./ pRoundTrip) < 1e-13);

%% p outside [0, 1], sigma <= 0 and NaN give NaN

assert(all(isnan(cobraNorminv([-0.1 1.1 NaN]))));
% sigma <= 0: NaN (R14; the documentation requires a positive sigma)
assert(isnan(cobraNorminv(0.3, 0, 0)) && isnan(cobraNorminv(0.3, 0, -1)) && isnan(cobraNorminv(0.3, 0, -Inf)));
assert(isnan(cobraNorminv(0.3, NaN)) && isnan(cobraNorminv(0.3, 0, NaN)));
assert(isequal(cobraNorminv([0 1], 5, 2), [-Inf Inf]));

%% scalar expansion, output size and class

assert(isequal(size(cobraNorminv(0.5 * ones(2, 3), 1, 2)), [2 3]));
assert(isequal(cobraNorminv(0.5, [1 2], [3 4]), [1 2]));
assert(isequal(size(cobraNorminv(zeros(0, 2))), [0 2]));
xSingle = cobraNorminv(single(0.975));
assert(isa(xSingle, 'single') && abs(xSingle - single(1.959963984540054)) < 1e-6);

%% errors: invalid and mismatched inputs, unsupported confidence-bound syntax

assert(verifyCobraFunctionError('cobraNorminv', 'inputs', {'a'}, ...
    'testMessage', 'cobraNorminv: inputs must be real numeric arrays.'));
assert(verifyCobraFunctionError('cobraNorminv', 'inputs', {[0.1 0.2], [1 2 3]}, ...
    'testMessage', 'cobraNorminv: non-scalar inputs must have the same size.'));
% the confidence-bound syntax norminv(p, mu, sigma, pCov, alpha) and [x, xLo, xUp] is not
% supported
syntaxMessage = 'cobraNorminv: the confidence-bound syntax (pCov, alpha, xLo, xUp) is not supported; use x = cobraNorminv(p, mu, sigma).';
assert(verifyCobraFunctionError('cobraNorminv', 'inputs', {0.5, 0, 1, eye(2), 0.05}, 'testMessage', syntaxMessage));
assert(verifyCobraFunctionError('cobraNorminv', 'inputs', {0.5, 0, 1}, 'outputArgCount', 3, 'testMessage', syntaxMessage));

%% parity with norminv (only where the Statistics and Machine Learning Toolbox is installed)

if exist('norminv', 'file') == 2 && license('test', 'Statistics_Toolbox')
    rng(20261103);
    pRandom = [rand(200, 1); 0; 1; 1e-300];
    muRandom = randn(203, 1);
    sigmaRandom = 0.1 + 2 * rand(203, 1);
    % both evaluate -sqrt(2)*erfcinv(2p); 1e-14 relative allows for rounding only
    assert(maxRelativeError(cobraNorminv(pRandom, muRandom, sigmaRandom), norminv(pRandom, muRandom, sigmaRandom)) < 1e-14);
    assert(isequal(isinf(cobraNorminv(pRandom)), isinf(norminv(pRandom))));
    fprintf('parity with norminv: passed\n');
else
    fprintf('skipped: Statistics and Machine Learning Toolbox not installed\n');
end

% change the directory
cd(currentDir)
