% the columns exercise both branches: nu < 1000 (betaincinv; the w form for p near 1/2) and
% nu >= 1000 (Cornish-Fisher expansion, exactly the normal quantile for nu = Inf). Against the
% exact values the largest ordinary difference measured on 2026-11-03 is 1.3e-14, hence 1e-13.
% Known differences (MathWorks R14 algorithm reproduced, recorded in the cobraTinv NOTE) get
% their own tolerance, about three times the measured difference:
%   p = 1e-300, nu = 1: betaincinv underflows to 0, so the result is -Inf (exact -3.18e299);
%   p = 1e-300, nu = 2.5 and 10: betaincinv in the extreme tail, 3.9e-9 and 1.0e-9;
%   p = 1e-300, nu = 1000 and 9000: expansion truncation, 2.75e-4 and 5.9e-9;
%   p = 1e-10 and 1 - 1e-12, nu = 1000: expansion truncation, 1.1e-11 and 2.7e-11.
% (p = 1e-300 with nu = 0.5 is -Inf exactly: the exact quantile, about -1e600, overflows.)
expectedInv = refInvExact;
expectedInv(1, nuGrid == 1) = -Inf;
tolerance = 1e-13 * ones(size(refInvExact));
tolerance(1, ismember(nuGrid, [2.5 10 9000])) = 2e-8;
tolerance(1, nuGrid == 1000) = 1e-3;
tolerance([2 6], nuGrid == 1000) = 1e-10;
for k = 1:numel(nuGrid)
    xValues = cobraTinv(pGrid', nuGrid(k));
    useRow = isRelative(expectedInv(:, k));
    relativeError = abs(xValues(useRow) - expectedInv(useRow, k)) ./ abs(expectedInv(useRow, k));
    fprintf('cobraTinv vs mpmath, nu = %g: max relative error %.2e\n', nuGrid(k), max(relativeError));
    assert(all(relativeError <= tolerance(useRow, k)));
    assert(isequal(xValues(~useRow), expectedInv(~useRow, k)));
end
% SciPy's t.ppf (Boost) clamps at -1e100, returns about 7e-17 instead of 0 at p = 0.5 and is
% off by up to 2e-3 relative in extreme tails and by up to 2e-11 in ordinary cases (for
% example t.ppf(0.025, 1)). Where it agrees with the exact values to 1e-10 it is compared at
% 2e-10 (that bound plus the accuracy of cobraTinv), which still checks the independent
% implementation on every column.
isScipyAccurate = abs(refInv - refInvExact) <= 1e-10 * abs(refInvExact) & isRelative(refInvExact);
assert(nnz(isScipyAccurate) >= 30);
for k = 1:numel(nuGrid)
    xValues = cobraTinv(pGrid', nuGrid(k));
    useRow = isScipyAccurate(:, k);
    assert(maxRelativeError(xValues(useRow), refInv(useRow, k)) < 2e-10);
end

%% very large nu: the expansion terms vanish and the result is the normal quantile

% regression check for a review finding: an earlier tail branch fired for nu > 1e200
assert(maxRelativeError(cobraTinv(0.025, [1e199 1e250 1e300]), cobraNorminv(0.025) * [1 1 1]) < 1e-15);

%% round trip with cobraTcdf and symmetry

% for nu < 1000 cobraTcdf(cobraTinv(p, nu), nu) = p to 1.2e-13 relative (measured), hence
% 1e-12; the expansion regime (nu >= 1000) is checked against the exact values above
pRoundTrip = [1e-200 1e-20 1e-5 0.01 0.2 0.45 0.4999]';
for nu = [0.3 1 4.5 50 999]
    xRoundTrip = cobraTinv(pRoundTrip, nu);
    isFiniteX = isfinite(xRoundTrip);
    assert(max(abs(cobraTcdf(xRoundTrip(isFiniteX), nu) - pRoundTrip(isFiniteX)) ./ pRoundTrip(isFiniteX)) < 1e-12);
end
for nu = [0.3 1 4.5 50 999 1000 2e4]
    % symmetry tinv(1 - p) = -tinv(1 - (1 - p)) holds exactly: both evaluate the same tail
    pUpper = 1 - pRoundTrip;
    assert(isequal(cobraTinv(pUpper, nu), -cobraTinv(1 - pUpper, nu)));
end
% p = 1e-200: with nu = 0.3 the exact quantile (about -exp(1530)) overflows; with nu = 1 the
% exact quantile is -3.18e199 but betaincinv underflows to 0, so both give -Inf (known
% difference, as the MathWorks formula)
assert(isequal(cobraTinv(1e-200, [0.3 1]), [-Inf -Inf]));

%% edge cases: p = 0, 0.5, 1; p outside [0, 1], nu <= 0 and NaN give NaN

assert(isequal(cobraTinv([0 0.5 1], 3), [-Inf 0 Inf]));
assert(isequal(cobraTinv([0 0.5 1], Inf), [-Inf 0 Inf]));
assert(all(isnan(cobraTinv([-0.1 1.1 NaN], 3))));
assert(all(isnan(cobraTinv([0.3 0.3 0.3], [0 -1 NaN]))));
% non-integer degrees of freedom
assert(abs(cobraTcdf(cobraTinv(0.9, 2.7), 2.7) - 0.9) < 1e-14);

%% scalar expansion, output size and class

assert(isequal(size(cobraTinv(0.9 * ones(2, 3), 4)), [2 3]));
assert(isequal(size(cobraTinv(0.9, [1 2 3 4])), [1 4]));
assert(isequal(cobraTinv([0.9 0.2], [3 4]), [cobraTinv(0.9, 3) cobraTinv(0.2, 4)]));
assert(isequal(size(cobraTinv(zeros(0, 3), 2)), [0 3]));
xSingle = cobraTinv(single(0.95), 10);
assert(isa(xSingle, 'single') && abs(xSingle - single(1.8124611228116758)) < 1e-6);

