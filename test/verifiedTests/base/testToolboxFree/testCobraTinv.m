% relative error over the entries whose reference is finite and non-zero; entries whose
% reference is 0 or +-Inf are compared exactly
isRelative = @(reference) reference ~= 0 & isfinite(reference);
relativeErrorOfColumns = @(value, reference) max([0; abs(value(isRelative(reference)) - reference(isRelative(reference))) ./ abs(reference(isRelative(reference)))]);
maxRelativeError = @(value, reference) relativeErrorOfColumns(value(:), reference(:));

%% call-site syntax tinv(0.95, n - 1) (calculateEPSILON) and the MathWorks documentation value

% doc: tinv(0.95, 10) = 1.8125; exact (mpmath, grid below) 1.8124611228116758
nSamples = 11;
x = cobraTinv(0.95, nSamples - 1);
assert(isscalar(x) && isa(x, 'double'));
assert(abs(x - 1.8125) < 5e-5);
assert(maxRelativeError(x, 1.8124611228116758) < 1e-14);
% nu = Inf is the normal quantile: tinv(0.975, Inf) = norminv(0.975) = 1.9600 (doc)
% (the lower tail 1 - 0.975 is computed in floating point, then the sign is flipped)
assert(cobraTinv(0.975, Inf) == sqrt(2) * erfcinv(2 * (1 - 0.975)));
assert(abs(cobraTinv(0.975, Inf) - 1.9600) < 5e-5);

