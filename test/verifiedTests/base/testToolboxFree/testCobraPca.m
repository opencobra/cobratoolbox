%% rank-deficient data: components orthogonal to the data are ignored in tsquared

% the 4th column is the sum of the first two, so the centred data has rank 3: warning
% cobraPca:ColRankDefX and tsquared from the first 3 components
rankDeficient = [ingredients(:, 1:3), ingredients(:, 1) + ingredients(:, 2)];
lastwarn('');
[coeff, score, latent, tsquared] = cobraPca(rankDeficient);
[warningMessage, warningId] = lastwarn;
assert(strcmp(warningId, 'cobraPca:ColRankDefX') && contains(warningMessage, 'Using only the first 3 components'));
assert(latent(4) < 1e-12 * latent(1));
expected = sum(score(:, 1:3) .^ 2 ./ latent(1:3)', 2);
assert(maxRel(tsquared, expected) < 1e-14);
assert(isequal(size(coeff), [4 4]));
% without tsquared there is no warning
lastwarn('');
[~, ~, ~] = cobraPca(rankDeficient);
assert(isempty(lastwarn));

