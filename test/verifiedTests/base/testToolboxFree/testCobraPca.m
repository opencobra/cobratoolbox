% Tolerances: two LAPACK SVDs of the same matrix agree to about eps*norm(X)/gap in the singular
% vectors, where gap is the distance to the nearest other singular value. For the Hald data
% norm(X) is about 100 (centred) to 250 (uncentred) and the smallest gap about 1.4 (in singular
% values), so coefficients agree to about 2e-14 absolute; 1e-12 absolute is used for the unit
% coefficient vectors, 1e-12 relative to the largest |score| for scores, 1e-12 relative for
% latent and explained (squared singular values, condition 2), and 1e-11 relative for tsquared
% (it divides by the smallest latent, 0.24 vs 518, losing about 3 digits of the absolute
% accuracy of the last score column).
maxAbs = @(a, b) max(abs(a(:) - b(:)));
maxRel = @(a, b) max(abs(a(:) - b(:)) ./ abs(b(:)));

%% call-site syntax [coeff, score, ~, ~, explained] = pca(X, 'Centered', false, 'Algorithm', 'als')

% dimensionalityReductionAndMultivariateAnalysis: uncentred data, d = n = 5 rows, p = 8 columns,
% so k = min(n, p) = 5 components; 'als' is computed by the SVD for complete data
[coeff, score, ~, ~, explained] = cobraPca(wideData, 'Centered', false, 'Algorithm', 'als');
assert(isequal(size(coeff), [8 5]) && isequal(size(score), [5 5]) && isequal(size(explained), [5 1]));
assert(maxAbs(coeff, refCoeffWide) < 1e-12);
assert(maxAbs(score, refScoreWide) < 1e-12 * max(abs(refScoreWide(:))));
assert(maxRel(explained, refExplainedWide') < 1e-12);
% the uncentred data is reproduced by score*coeff'
assert(maxAbs(score * coeff', wideData) < 1e-13);

%% all outputs for the call-site options, uncentred: latent = s.^2/n, tsquared, mu = 0

[coeff, score, latent, tsquared, explained, mu] = cobraPca(wideData, 'Centered', false, 'Algorithm', 'als');
assert(maxRel(latent, refLatentWide') < 1e-12 && maxRel(explained, refExplainedWide') < 1e-12);
% with as many components as rows, tsquared = n for every row (U is square orthogonal)
assert(maxRel(tsquared, refTsquaredWide') < 1e-12 && maxAbs(tsquared, 5 * ones(5, 1)) < 1e-12);
assert(isequal(mu, zeros(1, 8)));
assert(abs(sum(explained) - 100) < 1e-12);
% 'als' and 'svd' give the same result (both are the SVD solution here)
[coeffSvd, scoreSvd] = cobraPca(wideData, 'Centered', false);
assert(isequal(coeffSvd, coeff) && isequal(scoreSvd, score));

