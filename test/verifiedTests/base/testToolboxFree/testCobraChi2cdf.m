prepareTest();

% relative error over the entries whose reference is finite and non-zero; entries whose
% reference is 0 or +-Inf are compared exactly
isRelative = @(reference) reference ~= 0 & isfinite(reference);
relativeErrorOfColumns = @(value, reference) max([0; abs(value(isRelative(reference)) - reference(isRelative(reference))) ./ abs(reference(isRelative(reference)))]);
maxRelativeError = @(value, reference) relativeErrorOfColumns(value(:), reference(:));

%% call-site syntax chi2cdf([stats.chisquare], nBin - 1) (compareTwoSamplesStat)

% a row of statistics and a scalar degrees of freedom give a row of probabilities
stats = struct('chisquare', {0.5, 3, 40});
nBin = 3;
p = cobraChi2cdf([stats.chisquare], nBin - 1);
assert(isequal(size(p), [1 3]) && isa(p, 'double'));
% v = 2 is the exponential distribution with mean 2: P = 1 - exp(-x/2)
assert(maxRelativeError(p, -expm1(-[0.5 3 40] / 2)) < 1e-14);

%% closed forms: v = 1 (P = erf(sqrt(x/2))) and v = 2 (P = 1 - exp(-x/2))

xClosed = [1e-8 0.01 0.5 3.841458820694124 10 60]';
assert(maxRelativeError(cobraChi2cdf(xClosed, 1), erf(sqrt(xClosed / 2))) < 1e-14);
assert(maxRelativeError(cobraChi2cdf(xClosed, 1, 'upper'), erfc(sqrt(xClosed / 2))) < 1e-13);
assert(maxRelativeError(cobraChi2cdf(xClosed, 2), -expm1(-xClosed / 2)) < 1e-14);
assert(maxRelativeError(cobraChi2cdf(xClosed, 2, 'upper'), exp(-xClosed / 2)) < 1e-14);
% the 95% critical value with one degree of freedom is 1.959963984540054^2
assert(abs(cobraChi2cdf(3.841458820694124, 1) - 0.95) < 1e-15);

