% chi2cdf is gammainc(x/2, v/2) and SciPy's chi2 uses Cephes' igam/igamc: both are accurate to a
% few units in the last place on this grid, including the 1e-220 upper tails; 1e-13 relative
for k = 1:numel(vGrid)
    lowerValues = cobraChi2cdf(xGrid', vGrid(k));
    upperValues = cobraChi2cdf(xGrid', vGrid(k), 'upper');
    fprintf('cobraChi2cdf vs SciPy, v = %g: max relative error lower %.2e, upper %.2e\n', ...
        vGrid(k), maxRelativeError(lowerValues, refLower(:, k)), maxRelativeError(upperValues, refUpper(:, k)));
    assert(maxRelativeError(lowerValues, refLower(:, k)) < 1e-13);
    assert(maxRelativeError(upperValues, refUpper(:, k)) < 1e-13);
    assert(isequal(lowerValues(~isRelative(refLower(:, k))), refLower(~isRelative(refLower(:, k)), k)));
    assert(isequal(upperValues(~isRelative(refUpper(:, k))), refUpper(~isRelative(refUpper(:, k)), k)));
end

%% edge cases: x < 0, x = 0, x = Inf; v < 0 and NaN give NaN; non-integer v

assert(isequal(cobraChi2cdf([-Inf -1 0 Inf], 3), [0 0 0 1]));
assert(isequal(cobraChi2cdf([-Inf -1 0 Inf], 3, 'upper'), [1 1 1 0]));
assert(all(isnan(cobraChi2cdf([1 1 1], [-2 -Inf NaN]))));

%% v = 0 is a point mass at 0 (gammainc(x, 0) = 1; UNCONFIRMED for current chi2cdf, see NOTE)

% compareTwoSamplesStat calls chi2cdf(stat, nBin - 1), and nBin - 1 can be 0
assert(isequal(cobraChi2cdf([-1 0 0.5 40 Inf], 0), [0 1 1 1 1]));
assert(isequal(cobraChi2cdf([-1 0 0.5 40 Inf], 0, 'upper'), [1 0 0 0 0]));
assert(isequal(cobraChi2cdf([0.5 3 40], 1 - 1), [1 1 1]));
assert(isnan(cobraChi2cdf(NaN, 3)) && isnan(cobraChi2cdf(NaN, 3, 'upper')));
% v = 2.5 at x = 0.5 (SciPy grid value) is a non-integer degree of freedom
assert(maxRelativeError(cobraChi2cdf(0.5, 2.5), 0.13611637154141112) < 1e-14);

%% scalar expansion, output size and class

assert(isequal(size(cobraChi2cdf(ones(2, 3), 4)), [2 3]));
assert(isequal(size(cobraChi2cdf(1, [1 2 3 4])), [1 4]));
assert(isequal(cobraChi2cdf([1 2], [3 4]), [cobraChi2cdf(1, 3) cobraChi2cdf(2, 4)]));
assert(isequal(size(cobraChi2cdf(zeros(0, 3), 2)), [0 3]));
pSingle = cobraChi2cdf(single(3), 10);
assert(isa(pSingle, 'single') && abs(pSingle - single(0.018575936222140675)) < 1e-7);

%% errors: unsupported option and invalid or mismatched inputs

assert(verifyCobraFunctionError('cobraChi2cdf', 'inputs', {1, 2, 'lower'}, ...
    'testMessage', 'cobraChi2cdf: unsupported option ''lower'' (only ''upper'' is supported).'));
assert(verifyCobraFunctionError('cobraChi2cdf', 'inputs', {1, 2, 3}, ...
    'testMessage', 'cobraChi2cdf: unsupported option ''double'' (only ''upper'' is supported).'));
assert(verifyCobraFunctionError('cobraChi2cdf', 'inputs', {'a', 2}, ...
    'testMessage', 'cobraChi2cdf: inputs must be real numeric arrays.'));
assert(verifyCobraFunctionError('cobraChi2cdf', 'inputs', {[1 2], [1 2 3]}, ...
    'testMessage', 'cobraChi2cdf: non-scalar inputs must have the same size.'));

