% The COBRAToolbox: testDiscretizeFPKM.m
%
% Purpose:
%     - discretizeFPKM (rFASTCORMICS) discretizes FPKM values into expressed, unknown and not
%       expressed genes from a zFPKM transformation with half-Gaussian fits of the density. It
%       uses cobraKsdensity and cobraFitGauss1 (feature 20261111-152503-toolbox-free-remaining:
%       no Statistics or Curve Fitting Toolbox). This test checks the classes on synthetic data
%       with known groups, consistency between permuted samples, first-run reference counts, and
%       the figures (written to a temporary folder and removed).
%
% Function under test:
%     src/dataIntegration/transcriptomics/rFASTCORMICS/discretizeFPKM.m
%
% Tier (Constitution III-Coverage):
%     Tier 1 - no model, no solver, synthetic data. The counts are first-run reference values
%     (Tier 5): generated by the first run on 2026-11-11 (MATLAB R2025a, no solver involved), not
%     derived independently, so they guard consistency; the density and fit functions are checked
%     independently in testCobraKsdensity and testCobraFitGauss1.
%
% Coverage exemptions:
%     Not measured to 100% here: this test was added to cover the toolbox-free replacements
%     reached by discretizeFPKM (the default and the figure paths), not as a full back-fill.
%
% Known defects documented (NOT tested, NOT fixed here):
%     None found.
%
% Authors:
%     - Generated for feature 20261111-152503-toolbox-free-remaining, 2026-11-11.

% save the current path
currentDir = pwd;

% initialize the test
fileDir = fileparts(which('testDiscretizeFPKM'));
cd(fileDir);

% no solver or toolbox is needed
prepareTest();

%% zFPKM transformation with half-Gaussian fits (cobraKsdensity, cobraFitGauss1)

% synthetic FPKM values of two samples: a highly expressed group, a lowly expressed group and
% genes with zero FPKM
rng(20261111);
fpkmSample = [2 .^ (5 + randn(2000, 1)); 2 .^ (-1 + 1.5 * randn(800, 1)); zeros(200, 1)];
fpkm = [fpkmSample, fpkmSample(randperm(3000))];
discretizedFpkm = discretizeFPKM(fpkm, {'sample1', 'sample2'}, 0);
assert(isequal(size(discretizedFpkm), [3000 2]) && all(ismember(discretizedFpkm(:), [-1 0 1])));
% zero FPKM is never expressed, the highly expressed group is never 'not expressed', and most
% of the lowly expressed group is 'not expressed'
assert(all(discretizedFpkm(2801:3000, 1) == -1));
assert(~any(discretizedFpkm(1:2000, 1) == -1));
assert(mean(discretizedFpkm(2001:2800, 1) == -1) > 0.9);
% the second sample is a permutation of the first, so the classes are permuted with it
[~, order] = sort(fpkm(:, 1));
[~, orderPermuted] = sort(fpkm(:, 2));
assert(isequal(discretizedFpkm(order, 1), discretizedFpkm(orderPermuted, 2)));
% first-run reference counts (Tier 5, see header): expressed, unknown, not expressed
fprintf('discretizeFPKM counts (1, 0, -1): %d %d %d\n', sum(discretizedFpkm(:, 1) == 1), ...
    sum(discretizedFpkm(:, 1) == 0), sum(discretizedFpkm(:, 1) == -1));
assert(isequal([sum(discretizedFpkm(:, 1) == 1), sum(discretizedFpkm(:, 1) == 0), sum(discretizedFpkm(:, 1) == -1)], [1052 992 956]));

% with figures (written to a temporary folder and removed): the fitted curves are drawn from
% the fit structures over the range of the current axes
figureFolder = [tempname filesep];
mkdir(figureFolder);
defaultVisibility = get(0, 'DefaultFigureVisible');
set(0, 'DefaultFigureVisible', 'off');
discretizedWithFigures = discretizeFPKM(fpkm(:, 1), {'sample1'}, 1, figureFolder, '.png');
set(0, 'DefaultFigureVisible', defaultVisibility);
close all
assert(isequal(discretizedWithFigures, discretizedFpkm(:, 1)));
assert(numel(dir(fullfile(figureFolder, '*.png'))) + numel(dir(fullfile(figureFolder, 'Figures', '**', '*.png'))) > 0);
rmdir(figureFolder, 's');

% change the directory
cd(currentDir)
