"""Reference values for cobraNormcdf, cobraNorminv, cobraTcdf, cobraTinv,
cobraChi2cdf and cobraFcdf (feature 20261103-120403-toolbox-free-replacements, T005).

Independent reference: SciPy (scipy.stats.norm, t, chi2, f; methods cdf, sf, ppf).
For the Student t quantiles SciPy's t.ppf is not accurate everywhere (it clamps
at -1e100 and is off by up to 2e-3 relative in extreme tails, by about 2e-11 in
ordinary cases such as t.ppf(0.025, 1)), so those are ALSO computed with mpmath
at 50 significant digits (root of the regularized incomplete beta function).
Run with SciPy 1.16 and mpmath 1.3:

    python3 distributions.py

The output is MATLAB code (one matrix per function and tail, rows = first grid
input, columns = second grid input) that is pasted into the tests in
test/verifiedTests/base/testToolboxFree/. Values are printed with repr precision
(17 significant digits), so the pasted doubles are the SciPy doubles.
"""
import math

import numpy as np
import mpmath
import scipy
from scipy import stats


def mat(value):
    """Format one float as a MATLAB literal."""
    value = float(value)
    if math.isnan(value):
        return "NaN"
    if math.isinf(value):
        return "Inf" if value > 0 else "-Inf"
    return repr(value)


def print_vector(name, values):
    print(f"{name} = [{' '.join(mat(v) for v in values)}];")


def print_matrix(name, rows):
    print(f"{name} = [ ...")
    for row in rows:
        print("    " + " ".join(mat(v) for v in row))
    print("    ];")


print(f"% generated by specs/20261103-120403-toolbox-free-replacements/references/distributions.py, SciPy {scipy.__version__}, NumPy {np.__version__}, mpmath {mpmath.__version__}")

# ---------------------------------------------------------------- normal
x_norm = [-40, -8, -1, 0, 0.5, 3, 40]
mu_sigma = [(0, 1), (1, 2), (-3, 0.5)]
print("\n% ---- normal: rows = x, columns = (mu, sigma) pairs")
print_vector("xGrid", x_norm)
print_matrix("muSigma", [list(ms) for ms in mu_sigma])
print_matrix("refLower", [[stats.norm.cdf(x, mu, s) for (mu, s) in mu_sigma] for x in x_norm])
print_matrix("refUpper", [[stats.norm.sf(x, mu, s) for (mu, s) in mu_sigma] for x in x_norm])

p_grid = [1e-300, 1e-10, 0.025, 0.5, 0.95, 1 - 1e-12]
print("\n% ---- normal quantiles: rows = p, columns = (mu, sigma) pairs")
print_vector("pGrid", p_grid)
print_matrix("muSigma", [list(ms) for ms in mu_sigma])
print_matrix("refInv", [[stats.norm.ppf(p, mu, s) for (mu, s) in mu_sigma] for p in p_grid])

# ---------------------------------------------------------------- Student t
x_t = [-1e120, -40, -8, -1, 0, 0.5, 3, 40]
nu_t = [0.5, 1, 2.5, 10, 1000, 9000, 1e6, math.inf]
print("\n% ---- Student t cdf: rows = x, columns = nu")
print_vector("xGrid", x_t)
print_vector("nuGrid", nu_t)
print_matrix("refLower", [[stats.t.cdf(x, nu) if math.isfinite(nu) else stats.norm.cdf(x) for nu in nu_t] for x in x_t])
print_matrix("refUpper", [[stats.t.sf(x, nu) if math.isfinite(nu) else stats.norm.sf(x) for nu in nu_t] for x in x_t])

print("\n% ---- Student t quantiles: rows = p, columns = nu")
print_vector("pGrid", p_grid)
print_vector("nuGrid", nu_t)
print_matrix("refInv", [[stats.t.ppf(p, nu) if math.isfinite(nu) else stats.norm.ppf(p) for nu in nu_t] for p in p_grid])

mpmath.mp.dps = 50


def t_lower_tail(x, nu):
    """P(T < x) for x <= 0 at mpmath precision."""
    return mpmath.betainc(nu / 2, mpmath.mpf(1) / 2, 0, nu / (nu + x * x), regularized=True) / 2


def t_quantile_exact(p, nu):
    """Student t quantile at 50 digits: root of log P(T < x) = log p in u = log(-x)."""
    if p == 0.5:
        return 0.0
    p_tail = mpmath.mpf(min(p, 1 - p))
    if math.isinf(nu):
        x = mpmath.findroot(lambda x: mpmath.log(mpmath.ncdf(x)) - mpmath.log(p_tail), float(stats.norm.ppf(float(p_tail))), tol=1e-45)
    else:
        nu = mpmath.mpf(nu)
        # start from the leading tail term, then solve in u = log(-x)
        u0 = ((nu / 2 - 1) * mpmath.log(nu) - mpmath.log(mpmath.beta(nu / 2, mpmath.mpf(1) / 2)) - mpmath.log(p_tail)) / nu
        start = float(stats.t.ppf(float(p_tail), float(nu)))
        if math.isfinite(start) and start < 0 and start > -1e90:
            u0 = mpmath.log(-start)
        u = mpmath.findroot(lambda u: mpmath.log(t_lower_tail(-mpmath.exp(u), nu)) - mpmath.log(p_tail), u0, tol=1e-45)
        x = -mpmath.exp(u)
    return float(-x if p > 0.5 else x)


print("\n% ---- Student t quantiles from mpmath (50 digits): rows = p, columns = nu")
print_matrix("refInvExact", [[t_quantile_exact(p, nu) for nu in nu_t] for p in p_grid])

# ---------------------------------------------------------------- chi-square
x_chi2 = [0, 1e-3, 0.5, 1, 3, 40, 1000]
v_chi2 = [0.5, 1, 2.5, 10, 100]
print("\n% ---- chi-square cdf: rows = x, columns = v")
print_vector("xGrid", x_chi2)
print_vector("vGrid", v_chi2)
print_matrix("refLower", [[stats.chi2.cdf(x, v) for v in v_chi2] for x in x_chi2])
print_matrix("refUpper", [[stats.chi2.sf(x, v) for v in v_chi2] for x in x_chi2])

# ---------------------------------------------------------------- F
x_f = [1e-3, 0.5, 1, 3, 40, 1e4]
v12 = [(1, 1), (2.5, 10), (10, 2.5), (0.5, 100), (5, math.inf), (math.inf, 5), (math.inf, math.inf)]


def f_cdf(x, v1, v2, upper):
    """F cdf with the infinite-degree-of-freedom limits written out."""
    if math.isinf(v1) and math.isinf(v2):
        lower = 1.0 if x >= 1 else 0.0
        return 1.0 - lower if upper else lower
    if math.isinf(v2):  # v1 * F -> chi2(v1)
        return stats.chi2.sf(v1 * x, v1) if upper else stats.chi2.cdf(v1 * x, v1)
    if math.isinf(v1):  # v2 / F -> chi2(v2)
        return stats.chi2.cdf(v2 / x, v2) if upper else stats.chi2.sf(v2 / x, v2)
    return stats.f.sf(x, v1, v2) if upper else stats.f.cdf(x, v1, v2)


print("\n% ---- F cdf: rows = x, columns = (v1, v2) pairs")
print_vector("xGrid", x_f)
print_matrix("v1v2", [list(v) for v in v12])
print_matrix("refLower", [[f_cdf(x, v1, v2, False) for (v1, v2) in v12] for x in x_f])
print_matrix("refUpper", [[f_cdf(x, v1, v2, True) for (v1, v2) in v12] for x in x_f])
