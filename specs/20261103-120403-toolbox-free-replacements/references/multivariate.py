def t_quantile(p, nu):
    """Student t quantile for p > 1/2 by mpmath at 50 digits (SciPy's t.ppf can be off by
    about 2e-11 relative, see distributions.py)."""
    mpmath.mp.dps = 50
    p = mpmath.mpf(p)
    nu = mpmath.mpf(nu)

    def upper_tail_minus(t):
        return mpmath.betainc(nu / 2, mpmath.mpf(1) / 2, 0, nu / (nu + t * t), regularized=True) / 2 - (1 - p)

    start = mpmath.mpf(stats.t.ppf(float(p), float(nu)))
    return float(mpmath.findroot(upper_tail_minus, start))


def regress_ref(y, X, alpha=0.05, keep=None):
    """keep: column indices used in the fit (others get b = 0)."""
    n, p = X.shape
    if keep is None:
        keep = list(range(p))
    Xk = X[:, keep]
    rank = len(keep)
    bk = np.linalg.lstsq(Xk, y, rcond=None)[0]
    b = np.zeros(p)
    b[keep] = bk
    yhat = X @ b
    r = y - yhat
    nu = n - rank
    s2 = r @ r / nu
    tval = t_quantile(1 - alpha / 2, nu)
    cov = np.linalg.inv(Xk.T @ Xk)
    se = np.zeros(p)
    se[keep] = np.sqrt(s2 * np.diag(cov))
    bint = np.column_stack([b - tval * se, b + tval * se])
    h = np.einsum("ij,jk,ik->i", Xk, cov, Xk)
    if nu > 1:
        # leave-one-out from the definition: refit without observation i,
        # s_(i)^2 = SSE_(i)/(nu - 1), interval r_i -/+ t(nu - 1)*sqrt(1 - h_i)*s_(i)
        sigma_i = np.empty(n)
        for i in range(n):
            keep_rows = np.arange(n) != i
            b_i = np.linalg.lstsq(Xk[keep_rows], y[keep_rows], rcond=None)[0]
            res_i = y[keep_rows] - Xk[keep_rows] @ b_i
            sigma_i[i] = math.sqrt(res_i @ res_i / (nu - 1))
        ser = np.sqrt(1 - h) * sigma_i
        tval_r = t_quantile(1 - alpha / 2, nu - 1)
    else:
        # nu = 1: sqrt(1 - h)*rmse with the t quantile of nu = 1 (MathWorks branch; t UNCONFIRMED)
        ser = np.sqrt(1 - h) * math.sqrt(s2)
        tval_r = tval
    rint = np.column_stack([r - tval_r * ser, r + tval_r * ser])
    sse = r @ r
    tss = np.sum((y - y.mean()) ** 2)
    rss = np.sum((yhat - y.mean()) ** 2)
    R2 = 1 - sse / tss
    F = (rss / (rank - 1)) / s2
    pF = stats.f.sf(F, rank - 1, nu)
    return b, bint, r, rint, np.array([R2, F, pF, s2])


