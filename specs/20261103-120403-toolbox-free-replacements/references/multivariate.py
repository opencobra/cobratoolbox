def tiedrank(v):
    return stats.rankdata(v, method="average")


def has_ties(v):
    return len(np.unique(v)) < len(v)


def spearman_D(x, y):
    return float(np.sum((tiedrank(x) - tiedrank(y)) ** 2))


def spearman_exact_p(x, y):
    """Two-sided exact permutation p of Spearman's D (min(2*more significant tail, 1))."""
    rx, ry = tiedrank(x), tiedrank(y)
    D = np.sum((rx - ry) ** 2)
    perms = np.array(list(itertools.permutations(ry)))
    Dp = np.sum((perms - rx) ** 2, axis=1)
    lower = np.mean(Dp <= D)
    upper = np.mean(Dp >= D)
    return min(2 * min(lower, upper), 1.0)


def as89_upper_tail(D, n):
    """P(D' >= D) for Spearman's D, n >= 7, AS 89 Edgeworth series (Best & Roberts 1975)."""
    c = [0.2274, 0.2531, 0.1745, 0.0758, 0.1033, 0.3932, 0.0879, 0.0151, 0.0072, 0.0831,
         0.0131, 0.00046]
    b = 1.0 / n
    x = (6.0 * (D - 1) * b / (n * n - 1) - 1) * math.sqrt(1 / b - 1)
    y = x * x
    u = x * b * (c[0] + b * (c[1] + c[2] * b)
                 + y * (-c[3] + b * (c[4] + c[5] * b)
                        - y * b * (c[6] + c[7] * b
                                   - y * (c[8] - c[9] * b + y * b * (c[10] - c[11] * y)))))
    p = u / math.exp(y / 2) + stats.norm.sf(x)
    return min(max(p, 0.0), 1.0)


def spearman_as89_p(x, y):
    n = len(x)
    D = spearman_D(x, y)
    n3 = (n ** 3 - n) / 3
    return min(2 * as89_upper_tail(max(D, n3 - D), n), 1.0)


def kendall_K(x, y):
    n = len(x)
    K = 0
    for i in range(n):
        for j in range(i + 1, n):
            K += np.sign(x[i] - x[j]) * np.sign(y[i] - y[j])
    return K


def kendall_exact_ties_p(x, y):
    rx, ry = tiedrank(x), tiedrank(y)
    K = kendall_K(rx, ry)
    Ks = np.array([kendall_K(rx, p) for p in itertools.permutations(ry)])
    lower = np.mean(Ks <= K)
    upper = np.mean(Ks >= K)
    return min(2 * min(lower, upper), 1.0)


def kendall_normal_cc_p(x, y):
    K = kendall_K(x, y)
    res = stats.kendalltau(x, y, variant="b", method="asymptotic")
    z = stats.norm.isf(res.pvalue / 2)
    sd = abs(K) / z
    return min(2 * stats.norm.cdf(-(abs(K) - 1) / sd), 1.0), sd


def print_pair(label, x, y, kind):
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    n = len(x)
    ties = has_ties(x) or has_ties(y)
    if kind == "pearson":
        r = stats.pearsonr(x, y)
        rho, p, how = r.statistic, r.pvalue, "pearsonr"
    elif kind == "spearman":
        rho = stats.spearmanr(x, y).statistic
        if n < 10:
            p, how = spearman_exact_p(x, y), "exact enumeration"
        elif not ties:
            p, how = spearman_as89_p(x, y), "AS 89"
        else:
            p, how = stats.spearmanr(x, y).pvalue, "spearmanr t approximation"
    else:
        rho = stats.kendalltau(x, y, variant="b").statistic
        if not ties and n < 50:
            p, how = stats.kendalltau(x, y, variant="b", method="exact").pvalue, "kendalltau exact"
        elif ties and n < 10:
            p, how = kendall_exact_ties_p(x, y), "exact enumeration of midranks"
        else:
            p, how = kendall_normal_cc_p(x, y)[0], "normal + continuity correction"
    print(f"% {label}: {kind}, n = {n}, ties = {ties}, p by {how}")
    print(f"{label} = [{mat(rho)} {mat(p)}];")


