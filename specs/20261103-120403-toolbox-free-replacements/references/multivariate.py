def pca_ref(X, centered):
    n, p = X.shape
    mu = X.mean(axis=0) if centered else np.zeros(p)
    X0 = X - mu
    d = n - 1 if centered else n
    U, s, Vt = np.linalg.svd(X0, full_matrices=False)
    k = min(d, p)
    coeff = Vt.T[:, :k].copy()
    score = (U * s)[:, :k].copy()
    for j in range(k):
        i = np.argmax(np.abs(coeff[:, j]))
        if coeff[i, j] < 0:
            coeff[:, j] *= -1
            score[:, j] *= -1
    latent = s[:k] ** 2 / d
    explained = 100 * latent / latent.sum()
    tol = max(d, p) * np.spacing(latent[0])
    q = int(np.sum(latent > tol))
    tsq = np.sum(score[:, :q] ** 2 / latent[:q], axis=1)
    return coeff, score, latent, tsq, explained, mu


